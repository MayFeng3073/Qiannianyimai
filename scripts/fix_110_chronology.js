const data = JSON.parse(fs.readFileSync(file, 'utf8'));
let eventsTouched = 0, nodesTouched = 0, missingNodes = [], missingEvents = [];
let variedEvents = 0, totalNodes = 0;
const seenEvents = new Set();

for (const e of data.events || []) {
  const name = String(e.name || '').trim();
  const map = MAP[name];
  if (!map) { missingEvents.push(name); continue; }
  seenEvents.add(name);
  if (YEAR_OVERRIDES[name]) Object.assign(e, YEAR_OVERRIDES[name]);
  const years = new Set();
  for (const n of e.narratives || []) {
    totalNodes++;
    const title = String(n.title || '').trim();
    const yt = map[title];
    if (!yt) { missingNodes.push(name + '/' + title); continue; }
    years.add(yt);
    if (n.year_text !== yt) { n.year_text = yt; nodesTouched++; }
  }
  if (years.size > 1) variedEvents++;
  eventsTouched++;
}

fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');
