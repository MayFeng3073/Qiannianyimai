let filled = 0, kept = 0, missing = [];
for (const f of fs.readdirSync(dir).filter(x => x.startsWith('dynasty_'))) {
  const file = path.join(dir, f);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const dyn = String(data.dynasty && (data.dynasty.name || data.dynasty));
  const table = DESC[dyn];
  for (const k of data.keywords || []) {
    const key = String(k.name || '').trim();
    if (table && table[key]) {
      if (k.desc !== table[key]) { k.desc = table[key]; filled++; }
      else kept++;
    } else if (k.desc && !/重要概念。$/.test(k.desc)) {
      kept++;
    } else {
      missing.push(dyn + '/' + key);
    }
  }
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');
}
console.log('已重写', filled, '条；保留', kept, '条；仍缺释义', missing.length);
