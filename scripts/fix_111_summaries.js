const d = load();
let applied = 0;
for (const p of d.persons || []) {
  if (p.level !== 2) continue;
  const text = SUMMARY_FIX[p.name];
  if (typeof text !== 'string') continue;
  p.summary = text;
  applied++;
}
save(d);

const l2 = (d.persons || []).filter(p => p.level === 2);
const empty = l2.filter(p => !String(p.summary || '').replace(/\s/g, ''));
const templated = l2.filter(p => TEMPLATE_RE.test(String(p.summary || '')));
const outOfRange = l2.filter(p => len(p.summary) < 25 || len(p.summary) > 45);
const dist = { '25-29': 0, '30-34': 0, '35-39': 0, '40-42': 0, '43-45': 0, '超范围': 0 };
l2.forEach(p => {
  const n = len(p.summary);
  if (n >= 25 && n <= 29) dist['25-29']++;
  else if (n <= 34) dist['30-34']++;
  else if (n <= 39) dist['35-39']++;
  else if (n <= 42) dist['40-42']++;
  else if (n <= 45) dist['43-45']++;
  else dist['超范围']++;
});
const nums = l2.map(p => len(p.summary)).sort((a, b) => a - b);
console.log(`应用条数：${applied}/${Object.keys(SUMMARY_FIX).length}`);
console.log(`二级人物总数：${l2.length}，简介为空：${empty.length}`);
console.log(`仍匹配模板句：${templated.length}${templated.length ? ' — ' + templated.map(p => p.name).join('、') : ''}`);
console.log(`字数 min/max：${nums[0]}/${nums[nums.length - 1]}`);
console.log(`超出 25-45：${outOfRange.length}${outOfRange.length ? ' — ' + outOfRange.map(p => `${p.name}(${len(p.summary)})`).join('；') : ''}`);
console.log('字数分布：' + JSON.stringify(dist));
