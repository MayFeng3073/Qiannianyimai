function mergeFragments(items) {
  const out = [];
  for (let s of items) {
    s = (s || '').trim();
    if (!s) continue;
    if (s.length <= 6 && out.length > 0) {
      const prev = out[out.length - 1];
      out[out.length - 1] = prev.endsWith('、') || prev.endsWith('。') ? prev + s : prev + '、' + s;
      continue;
    }
    out.push(s);
  }
  return out;
}

