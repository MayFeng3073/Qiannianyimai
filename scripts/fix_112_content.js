function main() {
  const d = load();
  const persons = (d.persons || []);
  console.log('===== #1 历史影响力断句修复 =====');
  let total = 0;
  persons.forEach(p => {
    if (!Array.isArray(p.impact_list)) return;
    if (IMPACT_OVERRIDE[p.name]) { p.impact_list = IMPACT_OVERRIDE[p.name]; total++; return; }
    const merged = mergeFragments(p.impact_list);
    if (merged.join('') !== (p.impact_list || []).join('')) total++;
    p.impact_list = merged;
  });
  console.log('  修复影响描述段落的人物:', total);

  console.log('\n===== #2 主要奉献 description 按手写表覆盖 =====');
  let fixed = 0, unfixed = 0;
  persons.filter(p => p.level === 1).forEach(p => {
    const byName = TANG_WORKS[p.name] || {};
    (p.works || []).forEach(w => {
      if (!w) return;
      if (byName[w.name]) {
        w.description = byName[w.name];
        fixed++;
      } else if (w.description && (w.description.includes('……') || w.description.length > 60)) {
        w.description = String(w.description).replace(/…….*$/, '').replace(/[。，、；]+$/, '') + '。';
        unfixed++;
      }
    });
  });
  console.log('  手写覆盖的贡献项:', fixed, '；兜底清理:', unfixed);

  console.log('\n===== #3 后人评价统一裁剪为 2 条 =====');
  let trimmed = 0;
  persons.filter(p => p.level === 1).forEach(p => {
    if (Array.isArray(p.later_quotes) && p.later_quotes.length > 2) { p.later_quotes = p.later_quotes.slice(0, 2); trimmed++; }
  });
  console.log('  裁剪后人评价的人物:', trimmed);

  save(d);
  console.log('\n完成。');
}

main();
module.exports = { main, TANG_WORKS, IMPACT_OVERRIDE };