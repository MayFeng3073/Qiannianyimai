const d = load();
let applied = 0;
const missing = [];
for (const p of d.persons || []) {
  if (p.level !== 2) continue;
  const text = SUMMARY_FIX[p.name];
  if (typeof text === 'string') {
    p.summary = text;
    applied++;
  } else {
    missing.push(p.name);
  }
}
save(d);

const l2 = (d.persons || []).filter(p => p.level === 2);
const empty = l2.filter(p => !String(p.summary || '').trim());
const tpl = l2.filter(p => /时期的历史人物|从侧面展现|重要事迹为|历史风貌|是清朝时期/.test(String(p.summary || '')));
const lens = l2.map(p => len(p.summary));
const bad = l2.filter(p => /^[^，。]{1,6}是/.test(String(p.summary || '')) && String(p.summary || '').startsWith(p.name));
const out = l2.filter(p => len(p.summary) < 25 || len(p.summary) > 45);
const tooLong45 = l2.filter(p => len(p.summary) > 45);
const tooShort20 = l2.filter(p => len(p.summary) < 20);
const noEnd = l2.filter(p => !String(p.summary || '').endsWith('。'));
const manyComma = l2.filter(p => (String(p.summary || '').match(/[，；]/g) || []).length > 2);
const dist = { '25-29': 0, '30-34': 0, '35-39': 0, '40-45': 0 };
lens.forEach(n => {
  if (n < 25 || n > 45) return;
  if (n <= 29) dist['25-29']++;
  else if (n <= 34) dist['30-34']++;
  else if (n <= 39) dist['35-39']++;
  else dist['40-45']++;
});
console.log(`应用条数：${applied}/${Object.keys(SUMMARY_FIX).length}`);
console.log('未覆盖的二级人物：' + (missing.length ? missing.join('、') : '无'));
console.log('简介为空：' + empty.length);
console.log('仍含模板腔：' + tpl.length + (tpl.length ? '\n  ' + tpl.map(p => p.name).join('、') : ''));
console.log('以「姓名+是」开头：' + bad.length + (bad.length ? '\n  ' + bad.map(p => p.name).join('、') : ''));
console.log(`字数 min=${Math.min(...lens)} max=${Math.max(...lens)}`);
console.log('超出 25-45：' + (out.length ? '\n  ' + out.map(p => `${p.name}(${len(p.summary)})`).join('；') : '无'));
console.log('超过 45 字：' + tooLong45.length);
console.log('少于 20 字：' + tooShort20.length);
console.log('非「。」结尾：' + noEnd.length + (noEnd.length ? '\n  ' + noEnd.map(p => `${p.name}(${p.summary})`).join('；') : ''));
console.log('逗号/分号超过 2 个：' + manyComma.length + (manyComma.length ? '\n  ' + manyComma.map(p => `${p.name}(${len(p.summary)})`).join('；') : ''));
console.log('字数分布：' + JSON.stringify(dist));
