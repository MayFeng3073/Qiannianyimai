const d = load();
let applied = 0;
for (const p of d.persons || []) {
  if (p.level !== 2) continue;
  const text = SUMMARY_FIX[p.name];
  if (typeof text !== 'string') continue;
  p.summary = text;
  applied++;
}
save(d);

const l2 = (d.persons || []).filter(p => p.level === 2);
const empty = l2.filter(p => !String(p.summary || '').trim());
const tpl = l2.filter(p => /时期的历史人物|从侧面展现|重要事迹为|历史风貌/.test(p.summary || ''));
const bad = l2.filter(p => len(p.summary) < 25 || len(p.summary) > 45);
const tooShort = l2.filter(p => len(p.summary) < 20);
const counts = l2.map(p => len(p.summary));
const dist = { '<25': 0, '25-29': 0, '30-34': 0, '35-39': 0, '40-45': 0, '>45': 0 };
l2.forEach(p => {
  const n = len(p.summary);
  if (n < 25) dist['<25']++;
  else if (n <= 29) dist['25-29']++;
  else if (n <= 34) dist['30-34']++;
  else if (n <= 39) dist['35-39']++;
  else if (n <= 45) dist['40-45']++;
  else dist['>45']++;
});
console.log(`应用条数：${applied}/${Object.keys(SUMMARY_FIX).length}`);
console.log(`未覆盖二级人物：${l2.filter(p => !SUMMARY_FIX[p.name]).map(p => p.name).join('、') || '无'}`);
console.log(`二级简介为空：${empty.length ? empty.map(p => p.name).join('、') : 0}`);
console.log(`剩余模板化简介：${tpl.length ? tpl.map(p => p.name).join('、') : 0}`);
console.log(`少于 20 字：${tooShort.length ? tooShort.map(p => `${p.name}(${len(p.summary)})`).join('；') : 0}`);
console.log(`超出 45 字：${l2.filter(p => len(p.summary) > 45).length ? l2.filter(p => len(p.summary) > 45).map(p => `${p.name}(${len(p.summary)})`).join('；') : 0}`);
console.log(`字数超出 25-45：${bad.length ? '\n  ' + bad.map(p => `${p.name}(${len(p.summary)})`).join('；') : '无'}`);
console.log(`字数 min/max：${Math.min(...counts)}/${Math.max(...counts)}`);
console.log('字数分布：' + JSON.stringify(dist));
