// 标题合规检查：4-8 字、无标点
const PUNCT = /[，。、；：！？,.;:!?"'“”‘’（）()《》〈〉—…·\s]/;
function checkTitles() {
  let bad = [];
  Object.entries({ ...NARR_FIX, ...NARR_EXPAND_115 }).forEach(([id, arr]) => {
    arr.forEach(n => {
      if (n.title.length < 4 || n.title.length > 8) bad.push(`${id} 标题长度=${n.title.length}：「${n.title}」`);
      if (PUNCT.test(n.title)) bad.push(`${id} 标题含标点：「${n.title}」`);
    });
  });
  return bad;
}

/* 二级人物故事标题修正（原文标题超过 8 字，统一为简短短语） */
const STORY_TITLE_FIX = {
  '王景弘': '随郑和下西洋'
};

const d = load();
Object.entries(STORY_TITLE_FIX).forEach(([name, title]) => {
  const p = (d.persons || []).find(x => x.name === name);
  if (p && p.story) p.story.title = title;
});

const bad = checkTitles();
if (bad.length) { console.log('标题不合规：'); bad.forEach(b => console.log('  ' + b)); }

let applied = 0, missing = [];
for (const e of d.events) {
  const fix = NARR_EXPAND_115[e.id] || NARR_FIX[e.id];
  if (!fix) { missing.push(e.id + ' ' + e.name); continue; }
  e.narratives = fix.map(n => ({ year: e.start_year, tag: n.tag, title: n.title, description: n.description }));
  applied++;
}
save(d);
console.log(`事件经过手写覆盖：${applied}/${d.events.length}`);
