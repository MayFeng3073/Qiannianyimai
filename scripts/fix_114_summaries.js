const d = load();
const persons = d.persons || [];
let applied = 0;
const notFound = [];
const outRange = [];

persons.forEach(p => {
  if (p.level !== 2) return;
  const s = SUMMARY_FIX[p.name];
  if (!s) { notFound.push(p.name); return; }
  p.summary = s;
  applied++;
  const n = len(s);
  if (n < 25 || n > 45) outRange.push(`${p.name}(${n})`);
});

const l2 = persons.filter(p => p.level === 2);
const remainTemplate = l2.filter(p => /时期的历史人物|从侧面展现|重要事迹为|历史风貌/.test(p.summary || '')).length;
const lens = l2.map(p => len(p.summary)).sort((a, b) => a - b);

save(d);

console.log(`已应用简介: ${applied} 条`);
if (notFound.length) console.log(`未匹配到简介的人物(${notFound.length}): ${notFound.join('、')}`);
console.log(`剩余模板腔简介: ${remainTemplate} 条`);
console.log(`字数 min=${lens[0]} max=${lens[lens.length - 1]} avg=${(lens.reduce((a, b) => a + b, 0) / lens.length).toFixed(1)}`);
const buckets = { '25-29': 0, '30-34': 0, '35-39': 0, '40-42': 0, '43-45': 0 };
lens.forEach(n => {
  if (n < 30) buckets['25-29']++;
  else if (n < 35) buckets['30-34']++;
  else if (n < 40) buckets['35-39']++;
  else if (n < 43) buckets['40-42']++;
  else buckets['43-45']++;
});
console.log('字数分布: ' + Object.entries(buckets).map(([k, v]) => `${k}:${v}`).join('  '));
if (outRange.length) console.log(`超出 25-45 字的人物(${outRange.length}): ${outRange.join('、')}`);
