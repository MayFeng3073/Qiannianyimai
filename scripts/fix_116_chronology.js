const data = JSON.parse(fs.readFileSync(file, 'utf8'));
let eventsTouched = 0, nodesTouched = 0, nodesTotal = 0;
let variedEvents = 0, overrideCount = 0;
const missingNodes = [], missingEvents = [], extraNodes = [];

for (const e of data.events || []) {
  const name = String(e.name || '').trim();
  const map = MAP[name];
  if (!map) { missingEvents.push(name); continue; }
  eventsTouched++;
  if (YEAR_OVERRIDES[name]) {
    Object.assign(e, YEAR_OVERRIDES[name]);
    overrideCount++;
  }

  const yearSet = new Set();
  for (const n of e.narratives || []) {
    nodesTotal++;
    const title = String(n.title || '').trim();
    const yt = map[title];
    if (!yt) { missingNodes.push(name + '/' + title); continue; }
    yearSet.add(yt);
    if (n.year_text !== yt) { n.year_text = yt; nodesTouched++; }
  }
  if (yearSet.size > 1) variedEvents++;

  const nodeTitles = new Set((e.narratives || []).map(n => String(n.title || '').trim()));
  for (const title of Object.keys(map)) {
    if (!nodeTitles.has(title)) extraNodes.push(name + '/' + title);
  }
}

fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');

console.log('已编年事件', eventsTouched, '个，写入节点年份', nodesTouched, '条，节点总数', nodesTotal);
console.log('年份不同的事件', variedEvents, '个，区间修正', overrideCount, '个');
if (missingEvents.length) console.log('未覆盖事件:', missingEvents.join('、'));
if (missingNodes.length) console.log('未覆盖节点:', missingNodes.join('、'));
if (extraNodes.length) console.log('映射中多余节点:', extraNodes.join('、'));
console.log('缺失数:', missingEvents.length + missingNodes.length);
