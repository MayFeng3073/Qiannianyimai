const d = load();
let applied = 0;
const missing = [];
for (const p of d.persons || []) {
  if (p.level !== 2) continue;
  const text = SUMMARY_FIX[p.name];
  if (typeof text === 'string') {
    p.summary = text;
    applied++;
  } else {
    missing.push(p.name);
  }
}
save(d);

const l2 = (d.persons || []).filter(p => p.level === 2);
const empty = l2.filter(p => !String(p.summary || '').trim());
const tpl = l2.filter(p => /时期的历史人物|从侧面展现|重要事迹为|历史风貌/.test(String(p.summary || '')));
const lens = l2.map(p => len(p.summary));
const bad = l2.filter(p => String(p.summary || '').startsWith(p.name + '是'));
const out = l2.filter(p => len(p.summary) < 25 || len(p.summary) > 45);
const tooManyComma = l2.filter(p => (String(p.summary || '').match(/[，；]/g) || []).length > 2);
const dist = { '25-29': 0, '30-34': 0, '35-39': 0, '40-45': 0, '超45': 0, '少于25': 0 };
lens.forEach(n => {
  if (n < 25) dist['少于25']++;
  else if (n <= 29) dist['25-29']++;
  else if (n <= 34) dist['30-34']++;
  else if (n <= 39) dist['35-39']++;
  else if (n <= 45) dist['40-45']++;
  else dist['超45']++;
});
