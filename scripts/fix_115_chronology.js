const data = JSON.parse(fs.readFileSync(file, 'utf8'));
let eventCount = 0, nodeCount = 0, nodesTouched = 0, variedEvents = 0;
const missingEvents = [], missingNodes = [], overridesApplied = [];

for (const e of data.events || []) {
  const name = String(e.name || '').trim();
  const map = MAP[name];
  if (!map) { missingEvents.push(name); continue; }
  eventCount++;

  if (YEAR_OVERRIDES[name]) {
    const before = { start_year: e.start_year, end_year: e.end_year };
    Object.assign(e, YEAR_OVERRIDES[name]);
    if (before.start_year !== e.start_year || before.end_year !== e.end_year) {
      overridesApplied.push(name + ' ' + before.start_year + '-' + before.end_year + ' → ' + e.start_year + '-' + e.end_year);
    }
  }

  const years = new Set();
  for (const n of e.narratives || []) {
    nodeCount++;
    const title = String(n.title || '').trim();
    const yt = map[title];
    if (!yt) { missingNodes.push(name + '/' + title); continue; }
    years.add(yt);
    if (n.year_text !== yt) { n.year_text = yt; nodesTouched++; }
  }
  if (years.size > 1) variedEvents++;
}

// 反向检查：映射中存在、数据中不存在的事件
const unusedEvents = Object.keys(MAP).filter((name) => !(data.events || []).some((e) => String(e.name || '').trim() === name));

fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');

const pass = missingEvents.length === 0 && missingNodes.length === 0;
console.log('事件数:', eventCount, '节点数:', nodeCount, '写入节点年份:', nodesTouched, '条');
console.log('节点年份跨度不同的事件数:', variedEvents);
console.log('修正事件起止年:', overridesApplied.length ? overridesApplied.join('；') : '无');
if (unusedEvents.length) console.log('映射中未匹配到数据的事件:', unusedEvents.join('、'));
if (missingEvents.length) console.log('未覆盖事件:', missingEvents.join('、'));
if (missingNodes.length) console.log('未覆盖节点:', missingNodes.join('、'));
console.log('缺失事件数:', missingEvents.length, '缺失节点数:', missingNodes.length, pass ? 'PASS' : 'FAIL');
if (!pass) process.exitCode = 1;
