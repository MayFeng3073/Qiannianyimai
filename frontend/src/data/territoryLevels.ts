/**
 * 疆域示意图数据源
 * ================================
 * 把「朝代 → 控制程度」与「朝代 → 关键城市」从组件里抽出来，
 * 新增朝代时只改本文件，不必动 DynastyTerritoryMap.vue。
 *
 * 控制等级：
 *   2 = 直接统治（郡县/行省/布政使司）
 *   1 = 羁縻 · 都护 · 宗藩（设机构或名义臣属，不派流官）
 *   0 = 未及（地图上按「现代中国版图」灰底显示，仅作对照）
 *
 * 键名与 china-provinces.json 归一化后的省名一致（去掉省/市/自治区等后缀），
 * 域外条目直接使用 asia-countries.json 的国家名。
 */

export type Level = 0 | 1 | 2
export type LevelTable = Record<string, Level>

export interface City {
  name: string
  lon: number
  lat: number
  capital?: boolean
}

/** 组装一张等级表；未列出的地区一律视为 0（未及） */
function lv(direct: string[], loose: string[] = [], foreign: LevelTable = {}): LevelTable {
  const table: LevelTable = { ...foreign }
  for (const name of loose) table[name] = 1
  for (const name of direct) table[name] = 2
  return table
}

