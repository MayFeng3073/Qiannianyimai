/**
 * 事件人物引用判定
 * ==========================================================
 * 事件的 person_groups 里混有两类名字：
 *   1. 具体历史人物（可跳转人物详情页）
 *   2. 群体 / 方国 / 身份词（如「平民」「诸侯」「犬戎」「商朝贵族」）
 * 第 2 类本来就不该有详情页，也不该显示成可点击。
 * 这里提供统一判定，供 Event.vue 渲染时降级使用。
 */

/** 明确是具体人物，优先于群体词规则判断 */
const PERSON_WHITELIST = new Set([
  '商纣王', '周平王', '周桓公', '郑桓公', '虢石父', '虢公长父', '虢文公',
  '仲山甫', '南仲', '申后', '伯服', '微子', '管叔', '蔡叔', '霍叔',
  '周公', '姜太公', '大禹', '关龙逄', '赵梁', '干辛', '姒杼', '浇', '豷',
  '师般', '费仲', '恶来', '南宫括', '史佚', '胶鬲', '缯侯', '卫巫'
])

/** 完全等于这些词时视为群体 / 身份 */
const GROUP_EXACT = new Set([
  '商王', '周王', '夏王', '方国', '诸侯', '百姓', '平民', '国人', '贵族',
  '旧贵族', '功臣', '殷民', '商军', '周军', '夏王族', '周族', '商王族',
  '西周贵族', '商朝贵族', '商朝百姓', '商朝遗民', '商朝奴隶', '商朝俘虏',
  '姬姓宗室', '古圣王后裔', '后世儒家', '中国社会', '韦顾昆吾',
  '诸部', '联军', '大军', '朝臣', '群臣', '民众', '众人'
])

/** 包含这些词时视为群体 / 方国 / 身份 */
const GROUP_WORDS = [
  '氏', '族', '军', '民', '百姓', '贵族', '奴隶', '俘虏', '宗室',
  '国人', '功臣', '后裔', '诸侯', '部落', '联盟', '集团', '势力',
  '王朝', '社会', '方国', '王族'
]

export function isGroupRef(name: string): boolean {
  const n = (name || '').trim()
  if (!n) return false
  if (PERSON_WHITELIST.has(n)) return false
  if (GROUP_EXACT.has(n)) return true
  if (n.endsWith('方')) return true
  return GROUP_WORDS.some(w => n.includes(w))
}
